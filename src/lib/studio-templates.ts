export interface BuiltInStudioTemplate {
  id: string;
  name: string;
  description: string;
  category: "decorative" | "automotive" | "industrial" | "department";
  divisionLabel: string;
  departmentCode: string;
  templateType:
    | "marketing_promo"
    | "customer_service_qr"
    | "she_safety"
    | "ict_notice"
    | "hr_spotlight"
    | "general_announcement";
  canvasDoc: StudioCanvasDoc;
}

function bg(id: string): {
  backgroundPreset: string;
  backgroundCss: string;
  accentColor: string;
} {
  const found =
    STUDIO_BACKGROUNDS.find((b) => b.id === id) ?? STUDIO_BACKGROUNDS[0];
  return {
    backgroundPreset: found.id,
    backgroundCss: found.css,
    accentColor: found.accent,
  };
}

